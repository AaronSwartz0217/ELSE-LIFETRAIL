/* ---- 圆表 · 状态与稳定度（数值全部来自本站已有真实数据，口径写在各表下方） ---- */
const ringSVG = (pct, color) => {
  const r = 46, c = 2 * Math.PI * r;
  const off = c * (1 - Math.max(0, Math.min(100, pct)) / 100);
  return `<svg viewBox="0 0 120 120" width="128" height="128">
    <circle cx="60" cy="60" r="${r}" fill="none" stroke="var(--w-10)" stroke-width="10"/>
    <circle cx="60" cy="60" r="${r}" fill="none" stroke="${color}" stroke-width="10" stroke-linecap="round"
      stroke-dasharray="${c.toFixed(2)}" stroke-dashoffset="${off.toFixed(2)}" transform="rotate(-90 60 60)"/>
    <text x="60" y="60" text-anchor="middle" dominant-baseline="central"
      fill="var(--t1)" font-size="27" font-weight="600">${pct}%</text></svg>`;
};
const ymd = d => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

/* 状态：取最近一次 Human 3.0 四象限快照，按 L0–L3 折算 */
function stateRing(snaps) {
  if (!snaps || !snaps.length) return null;
  const last = snaps.slice().sort((a, b) => String(a.taken_at).localeCompare(String(b.taken_at))).pop();
  const s = last.scores || {};
  const v = Object.values(s).map(Number);
  if (!v.length) return null;
  const avg = v.reduce((a, b) => a + b, 0) / v.length;
  return { pct: Math.round(avg / 3 * 100), avg, at: last.taken_at,
           detail: Object.entries(s).map(([k, x]) => `${k} ${x}`).join(' · ') };
}

/* 当前行为的完成度 · 由每日问答的完成情况确定，本人确认后手工更新 */
