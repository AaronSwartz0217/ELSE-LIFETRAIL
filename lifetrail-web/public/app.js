/* LifeTrail 前端逻辑
 * 后端可用时走 API；未启动时回退到内置演示数据（页脚显示"离线演示"）。
 * 图表全部为原生 SVG 手绘，无第三方依赖。 */
const $ = s => document.querySelector(s);
const API_BASE = location.protocol === 'file:' ? 'http://127.0.0.1:3217' : '';
/* 本地访问令牌：由 server.js 在返回 index.html 时注入。
   直接以 file:// 打开时拿不到令牌，接口会拒绝，页面退回离线演示数据。 */
const LT_TOKEN = document.querySelector('meta[name="lt-token"]')?.content || '';
const ltHeaders = () => LT_TOKEN
  ? { 'Content-Type': 'application/json', 'X-LifeTrail-Token': LT_TOKEN }
  : { 'Content-Type': 'application/json' };

const api = async (u, opt) => {
  const r = await fetch(API_BASE + u, {
    method: opt ? (opt.m || 'POST') : 'GET',
    headers: ltHeaders(),
    body: opt ? JSON.stringify(opt.b || {}) : undefined
  });
  const data = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(data.error || `接口错误 ${r.status}`);
  return data;
};

/* 静态资源基址：本地服务下 index.html 与资源同目录（基址为空串）；
   GitHub Pages 的根入口把资源放在 lifetrail-web/public/ 下。
   直接由本脚本自身的 src 反推，两种环境都不用改代码。 */
const LT_BASE = (() => {
  const s = document.currentScript;
  return s && s.src ? s.src.replace(/[^/]*$/, '') : '';
})();

