/* 运行期兜底：任何未捕获错误都写到页脚，不开 DevTools 也能看到线索 */
window.addEventListener('error', ev => {
  const msg = (ev && (ev.message || (ev.error && ev.error.message))) || '未知错误';
  console.error('[LifeTrail] 未捕获错误：', (ev && ev.error) || msg);
  const f = document.querySelector('.foot');
  if (f) f.textContent = '运行出错：' + msg + '（按 F12 看控制台细节）';
});

