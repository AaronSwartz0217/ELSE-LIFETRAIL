/* 分组柱状图：动态数量 · 逐月
 * 横轴按月铺满全部记录（2016 → 最后一个有记录的月），左右滚动查看；
 * 左侧纵轴单独渲染成固定列，横向滚动时保持不动。 */
const MONTH_SLOT = 32, AXIS_W = 32, BAR_H = 190, BAR_PAD_T = 12, BAR_PAD_B = 38;
function renderBarChart(container, monthly) {
  const { months, logs, actions, judgments } = monthly;
  const base = BAR_H - BAR_PAD_B;
  // 纵轴顶端要盖过最高柱：原来 max 取原值、刻度按 step 递增，
  // 27 篇时刻度只到 21，最高的那根会冲出网格线。这里把 max 向上取整到 step 的倍数。
  const rawMax = Math.max(4, ...logs, ...actions, ...judgments);
  const step = Math.max(1, Math.ceil(rawMax / 4));
  const max = Math.ceil(rawMax / step) * step;
  const y = v => BAR_PAD_T + (base - BAR_PAD_T) * (1 - v / max);
  const barW = Math.min(8, (MONTH_SLOT - 10) / 3);

  // 卡片标题的年份区间跟着横轴走，不再写死「2016–2026」
  const titleEl = $('#monthChartTitle');
  if (titleEl && months.length) {
    const y0 = months[0].slice(0, 4), y1 = months[months.length - 1].slice(0, 4);
    titleEl.textContent = `动态数量 · 逐月（${y0}–${y1}，左右滚动查看）`;
  }

  // 纵轴列：固定宽度，不随横向滚动移动
  const axisEl = $('#chartYAxis');
  if (axisEl) {
    let a = `<svg viewBox="0 0 ${AXIS_W} ${BAR_H}" width="${AXIS_W}" height="${BAR_H}">`;
    for (let v = 0; v <= max; v += step) {
      a += `<line x1="0" y1="${y(v)}" x2="${AXIS_W}" y2="${y(v)}" stroke="${C_GRID}"/>` +
           `<text x="${AXIS_W - 8}" y="${y(v) + 3}" font-size="9" fill="${C_TXT}" text-anchor="end">${v}</text>`;
    }
    axisEl.innerHTML = a + '</svg>';
  }

  const W = months.length * MONTH_SLOT + 12;
  let s = `<svg viewBox="0 0 ${W} ${BAR_H}" width="${W}" height="${BAR_H}">`;
  for (let v = 0; v <= max; v += step) {
    s += `<line x1="0" y1="${y(v)}" x2="${W}" y2="${y(v)}" stroke="${C_GRID}"/>`;
  }
  // 年份分隔线 + 该年居中标签
  months.forEach((m, i) => {
    const [yy, mm] = m.split('-');
    if (mm !== '01') return;
    const x0 = MONTH_SLOT * i;
    let n = 1;
    while (n < 12 && months[i + n] && months[i + n].slice(0, 4) === yy) n++;
    s += `<line x1="${x0}" y1="${BAR_PAD_T}" x2="${x0}" y2="${base}" stroke="var(--w-07)"/>` +
         `<text x="${x0 + MONTH_SLOT * n / 2}" y="${BAR_H - 5}" font-size="10" fill="var(--t2)"
            text-anchor="middle">${yy}</text>`;
  });
  s += `<line x1="0" y1="${base}" x2="${W}" y2="${base}" stroke="var(--w-22)"/>`;
  months.forEach((m, i) => {
    const cx = MONTH_SLOT * i + MONTH_SLOT / 2;
    const g = [
      [logs[i], C_LOG, '日志'], [actions[i], C_ACT, '动作'], [judgments[i], C_JDG, '判断']
    ];
    g.forEach(([v, col, name], j) => {
      if (!v) return;
      const bx = cx - (barW * 3 + 6) / 2 + j * (barW + 3);
      s += `<rect x="${bx}" y="${y(v)}" width="${barW}" height="${base - y(v)}"
              rx="2" fill="${col}"><title>${m} · ${name} ${v}</title></rect>`;
    });
    s += `<text x="${cx}" y="${base + 16}" font-size="8.5" fill="${C_TXT}"
            text-anchor="middle">${m.slice(5)}</text>`;
  });
  // 转折点：贯穿全高的细红竖线（像刻度），整列可点 → 弹出该转折的具体内容与原因
  TURNINGS.forEach(t => {
    const mi = months.indexOf(t.at);
    if (mi < 0) return;
    const x = MONTH_SLOT * mi + MONTH_SLOT / 2;
    s += `<line x1="${x}" y1="0" x2="${x}" y2="${base}" stroke="${C_TP_RED}"
            stroke-width="1" stroke-opacity=".72"/>`;
    s += `<circle cx="${x}" cy="3.5" r="2" fill="${C_TP_RED}"/>`;
    s += `<rect x="${x - 5}" y="0" width="10" height="${base}" class="tp-hit"
            data-tp="${t.no}" fill="transparent">
            <title>转折点 ${String(t.no).padStart(2, '0')} · ${t.name}（${t.at}）</title></rect>`;
  });
  s += '</svg>';
  container.innerHTML = s;
  updateMonthArrows();
}

