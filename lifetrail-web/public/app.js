/* 3D 倾斜：跟随鼠标轻微转动，离开回正 */
function bindTilt(el) {
  if (REDUCED) return;
  el.addEventListener('mousemove', e => {
    const r = el.getBoundingClientRect();
    const px = (e.clientX - r.left) / r.width - .5, py = (e.clientY - r.top) / r.height - .5;
    el.style.transform = `perspective(720px) rotateY(${(px * 7).toFixed(2)}deg) rotateX(${(-py * 7).toFixed(2)}deg)`;
  });
  el.addEventListener('mouseleave', () => { el.style.transform = ''; });
}

/* 粒子星图：每颗粒子=一篇日志，按月份横向分布，缓慢上浮，鼠标靠近时躲开 */
function startRevParticles() {
  const c = $('#revCanvas'); if (!c) return;
  const ctx = c.getContext('2d');
  const H = 230;
  function resize() { c.width = Math.max(320, c.clientWidth || 1040); c.height = H; }
  resize();
  const parts = [];
  const total = MONTH_AXIS.length;
  MONTH_AXIS.forEach((m, i) => {
    const n = LOG_BY_MONTH[m] || 0;
    for (let k = 0; k < n; k++) {
      const x = (i + .5) / total * (c.width - 24) + 12;
      parts.push({ x, bx: x, y: 16 + Math.random() * (H - 32),
        vy: REDUCED ? 0 : -(0.10 + Math.random() * 0.30),
        r: 1 + Math.random() * 1.7, a: 0.22 + Math.random() * 0.5, h: i / total });
    }
  });
  const mouse = { x: -999, y: -999 };
  c.addEventListener('mousemove', e => {
    const r = c.getBoundingClientRect();
    mouse.x = (e.clientX - r.left) * (c.width / r.width);
    mouse.y = (e.clientY - r.top) * (H / r.height);
  });
  c.addEventListener('mouseleave', () => { mouse.x = mouse.y = -999; });

  function draw() {
    ctx.clearRect(0, 0, c.width, H);
    for (const p of parts) {
      // canvas 不吃 var()，这里的颜色只能写死（上游 col 同理）
      const col = p.h < .55 ? '143,163,191' : (p.h < .86 ? '216,180,122' : '245,245,247');
      ctx.beginPath();
      ctx.fillStyle = `rgba(${col},${p.a})`;
      ctx.arc(p.x, p.y, p.r, 0, 6.2832);
      ctx.fill();
    }
  }
  cancelAnimationFrame(REV_RAF);
  if (REDUCED) { draw(); return; }
  (function frame() {
    if (!$('#p-review')?.classList.contains('on')) return;   // 离开页面即停，不空转
    for (const p of parts) {
      p.y += p.vy;
      if (p.y < 6) p.y = H - 6;
      if (mouse.x > -900) {
        const dx = p.x - mouse.x, dy = p.y - mouse.y, d = Math.hypot(dx, dy);
        if (d < 72 && d > .5) { p.x += dx / d * 1.7; p.y += dy / d * 1.7; }
      }
      p.x += (p.bx - p.x) * .02;
    }
    draw();
    REV_RAF = requestAnimationFrame(frame);
  })();
}

