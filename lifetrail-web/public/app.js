async function loadPlan() {
  planBind(); planBindBar();
  try {
    let list = await api('/api/boards');
    if (!list.boards.length) {                            // 首开：写入 ta求职白板 的初始内容
      await api('/api/boards', { b: seedBoard() });
      list = await api('/api/boards');
    }
    BOARD_LIST = list.boards;
    if (list.dir) $('#boardDir').textContent = list.dir;
    const keep = BOARD && BOARD_LIST.some(b => b.id === BOARD.id) ? BOARD.id : BOARD_LIST[0].id;
    await openBoard(keep);
    if (!BOARD) throw new Error('白板详情加载失败');
    console.info('[loadPlan] 已加载白板：', BOARD && BOARD.id, '便签数：', BOARD && BOARD.notes.length);
  } catch (err) {
    console.warn('[loadPlan] 接口不可用，退回离线白板：', err && err.message);
    markOffline();
    if (!BOARD) {                                         // 离线时退回内存里的初始内容
      const s = seedBoard();
      BOARD = { id: 'offline', ...s, done: [] };
      renderTabs(); renderWall();
    }
  }
  setTimeout(updateScrollArrows, 80);
}

