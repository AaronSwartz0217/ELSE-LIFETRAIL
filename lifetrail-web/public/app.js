/* 日志分：近 4 周平均每周篇数 ÷ 3（一周 3 篇为达标线，高于按 100% 封顶） */
function logScore(logs) {
  const WEEKS = 4, PER_WEEK = 3, days = WEEKS * 7;
  const today = new Date();
  const from = new Date(today); from.setDate(from.getDate() - (days - 1));
  const a = ymd(from), b = ymd(today);
  const n = (logs || []).filter(l => {
    const d = String(l.date || '').slice(0, 10);
    return d >= a && d <= b;
  }).length;
  const perWeek = n / WEEKS;
  return { pct: Math.min(100, Math.round(perWeek / PER_WEEK * 100)),
           n, perWeek, weeks: WEEKS, target: PER_WEEK };
}

