function planBind() {
  const wall = $('#planWall');
  if (wall.dataset.bound === '1') return;
  wall.dataset.bound = '1';

  wall.addEventListener('click', e => {
    if (PLAN_DRAGGED) { PLAN_DRAGGED = false; return; }
    const note = e.target.closest('.note'); if (!note) return;
    const act = e.target.closest('[data-act]')?.dataset.act;
    const id = note.dataset.id;
    if (act === 'check') {
      BOARD.done = BOARD.done.includes(id) ? BOARD.done.filter(x => x !== id) : [...BOARD.done, id];
      renderWall(); saveBoard(); return;
    }
    const item = BOARD.notes.find(n => n.id === id);
    if (item && item.points && item.points.length) { BOARD_OPEN[id] = !BOARD_OPEN[id]; renderWall(); }
  });

  // 拖拽：换列 + 列内插位。点与拖共用 pointer：位移超过 4px 才升级为拖拽，
  // 拖过之后置 PLAN_DRAGGED，让随后补发的 click 不再误触「展开」。
  // 落点不是「塞到列尾」，而是光标当前夹在哪两张便签之间就插哪：
  // 靠一个与被拖便签等高的占位块把位置撑开，后面的便签自动往下让。
  let drag = null;

  /* 光标落在哪一列的哪道缝上：{ col, idx, colEl }；不在任何列上返回 null。
     idx = 该列里「中线在光标上方」的便签数。
     被拖的那张已脱离文档流（position:fixed），本来就不该参与比较。 */
  function dropSpot(x, y, skip) {
    const colEl = document.elementFromPoint(x, y)?.closest('.wall-col');
    if (!colEl) return null;
    const kids = [...colEl.querySelectorAll(':scope > .note')].filter(el => el !== skip);
    const idx = kids.filter(el => {
      const r = el.getBoundingClientRect();
      return y > r.top + r.height / 2;
    }).length;
    return { col: Number(colEl.dataset.col), idx, colEl };
  }

  /* 占位块挪到目标缝上；目标是 null（悬在删除 / 编辑区上）就先收起来 */
  function placeGhost(spot) {
    const g = drag.ghost; if (!g) return;
    if (!spot) { if (g.parentNode) g.remove(); return; }
    const kids = [...spot.colEl.querySelectorAll(':scope > .note')].filter(el => el !== drag.el);
    spot.colEl.insertBefore(g, kids[spot.idx] || null);
  }

  const onMove = e => {
    if (!drag) return;
    if (!drag.moved) {
      if (Math.abs(e.clientX - drag.sx) + Math.abs(e.clientY - drag.sy) <= 4) return;
      const r = drag.el.getBoundingClientRect();
      drag.moved = true;
      drag.ox = drag.sx - r.left;
      drag.oy = drag.sy - r.top;
      drag.el.classList.add('dragging');
      drag.el.style.width = r.width + 'px';
      // 占位块撑出被拖便签那么高的一段空位，别的便签就会自己让开
      drag.ghost = document.createElement('div');
      drag.ghost.className = 'note-ghost';
      drag.ghost.style.height = r.height + 'px';
      armDropZones(true);
    }
    drag.el.style.left = (e.clientX - drag.ox) + 'px';
    drag.el.style.top = (e.clientY - drag.oy) + 'px';
    const zone = dropZoneAt(e.clientX, e.clientY);
    highlightDropZone(zone);
    // 悬在删除 / 编辑区上时先收起占位块，免得「扔不扔」和「插在哪」两个提示打架
    const spot = zone ? null : dropSpot(e.clientX, e.clientY, drag.el);
    if (spot || zone) { placeGhost(spot); drag.spot = spot; }
    document.querySelectorAll('.wall-col').forEach(c => c.classList.toggle('over', !!spot && c === spot.colEl));
  };
  const onUp = e => {
    if (!drag) return;
    const { id, moved, ghost, spot } = drag;
    drag = null;
    document.removeEventListener('pointermove', onMove);
    document.removeEventListener('pointerup', onUp);
    document.body.classList.remove('dragging');     // 松手恢复：便签里的文字又能正常选中
    armDropZones(false); highlightDropZone(null);
    document.querySelectorAll('.wall-col').forEach(c => c.classList.remove('over'));
    if (!moved) return;
    PLAN_DRAGGED = true;
    if (ghost && ghost.parentNode) ghost.remove();
    const zone = dropZoneAt(e.clientX, e.clientY);
    if (zone) {                                     // 落到区域上：删除 / 编辑，不再改位置
      renderWall();                                 // 先把被拖起来的样式清掉，再执行动作
      if (zone.id === 'dropDel') deleteNote(id); else openNoteModal(id);
      return;
    }
    // 插入占位块停的那道缝（松手时光标若已滑出白板，就认它最后一次停的位置）；
    // 光标自始至终没进过白板，则退回「追加到第一列末尾」的老行为。
    const cols = BOARD.cols.map(c => c.filter(x => x !== id));
    const ci = spot && Number.isInteger(spot.col) && cols[spot.col] ? spot.col : 0;
    const idx = spot ? Math.max(0, Math.min(spot.idx, cols[ci].length)) : cols[ci].length;
    cols[ci].splice(idx, 0, id);
    BOARD.cols = cols;
    renderWall(); saveBoard();
  };
  wall.addEventListener('pointerdown', e => {
    const note = e.target.closest('.note'); if (!note) return;
    if (e.target.closest('button')) return;
    if (e.button !== 0) return;                     // 只认左键
    // 阻止默认行为：否则按住便签拖动时，浏览器会顺手把便签里的文字一起框选。
    // 便签正文仍可正常选中——这里只在按下的那一刻拦一次，不常驻禁选。
    e.preventDefault();
    document.body.classList.add('dragging');
    drag = { el: note, id: note.dataset.id, sx: e.clientX, sy: e.clientY, moved: false, ox: 0, oy: 0 };
    document.addEventListener('pointermove', onMove);
    document.addEventListener('pointerup', onUp);
  });
}

function planBindBar() {
  const tabs = $('#boardTabs');
  if (tabs.dataset.bound !== '1') {
    tabs.dataset.bound = '1';
    tabs.addEventListener('click', e => {
      if (TAB_DRAGGED) { TAB_DRAGGED = false; return; }   // 刚拖过，这一次补发的 click 不算
      const tab = e.target.closest('.board-tab'); if (!tab) return;
      if (BOARD && tab.dataset.id === BOARD.id) return;
      openBoard(tab.dataset.id);
    });
    tabs.addEventListener('dblclick', e => {
      const tab = e.target.closest('.board-tab'); if (!tab) return;
      renameBoardFromTab(tab.dataset.id);
    });
    /* 标签也能拖：拖到「删除」区即删板，拖到「重命名 / 编辑」区即改名。
       位移超过 4px 才算拖，避免和「点一下切白板 / 双击改名」打架。 */
    let tabDrag = null;
    const onTabMove = e => {
      if (!tabDrag) return;
      if (!tabDrag.moved) {
        if (Math.abs(e.clientX - tabDrag.sx) + Math.abs(e.clientY - tabDrag.sy) <= 4) return;
        tabDrag.moved = true;
        tabDrag.el.classList.add('dragging');
        armDropZones(true);
      }
      highlightDropZone(dropZoneAt(e.clientX, e.clientY));
    };
    const onTabUp = e => {
      if (!tabDrag) return;
      const { el, id, moved } = tabDrag;
      tabDrag = null;
      document.removeEventListener('pointermove', onTabMove);
      document.removeEventListener('pointerup', onTabUp);
      el.classList.remove('dragging');
      armDropZones(false); highlightDropZone(null);
      if (!moved) return;
      TAB_DRAGGED = true;
      const zone = dropZoneAt(e.clientX, e.clientY);
      if (!zone) return;
      if (zone.id === 'dropDel') deleteBoard(id); else renameBoardFromTab(id);
    };
    tabs.addEventListener('pointerdown', e => {
      const tab = e.target.closest('.board-tab'); if (!tab) return;
      if (e.button !== 0) return;
      tabDrag = { el: tab, id: tab.dataset.id, sx: e.clientX, sy: e.clientY, moved: false };
      document.addEventListener('pointermove', onTabMove);
      document.addEventListener('pointerup', onTabUp);
    });
  }
  const form = $('#planAddForm');
  if (form.dataset.bound !== '1') {
    form.dataset.bound = '1';
    form.addEventListener('submit', e => {
      e.preventDefault();
      if (!BOARD) {                                    // 不再静默：白板没加载好时给出提示并补一次加载
        const c = $('#planCount'); if (c) c.textContent = '白板还没加载好，正在重新加载…';
        console.warn('[planAdd] 提交被忽略：BOARD 为空，尝试重新加载白板');
        loadPlan();
        return;
      }
      openNoteModal();                                 // 弹出小框：主题 + 内容都在这写
    });
    $('#noteCancel').addEventListener('click', closeNoteModal);
    $('#noteConfirm').addEventListener('click', confirmNote);
    const noteMask = $('#noteModal');
    noteMask.addEventListener('click', e => { if (e.target === noteMask) closeNoteModal(); });
    noteMask.addEventListener('keydown', e => {
      if (e.key === 'Escape') { closeNoteModal(); return; }
      if (e.key === 'Enter' && (e.ctrlKey || e.metaKey)) { e.preventDefault(); confirmNote(); }
    });
    $('#noteTitle').addEventListener('keydown', e => {
      if (e.key === 'Enter') { e.preventDefault(); confirmNote(); }   // 主题行回车=贴上；内容框回车=换行
    });
    $('#boardNew').addEventListener('click', () => {
      const input = $('#boardNewName');
      const name = (input.value || '').trim() || '未命名白板';
      const fresh = { name, notes: [{ id: 'n1', title: '这块白板还是空的', tags: ['说明'],
        body: '在下面输入框里写一件要做的事，回车贴上来。', points: [], more: '' }],
        cols: [['n1'], [], []], done: [] };
      api('/api/boards', { b: fresh }).then(r => {
        input.value = '';
        return api('/api/boards').then(list => { BOARD_LIST = list.boards; renderTabs(); return openBoard(r.id); });
      }).catch(markOffline);
    });
  }
}

/* 「＋ 贴上」或「拖到重命名 / 编辑区」弹出的小框：主题 + 内容。
   不带 noteId ＝ 新建便签；带 noteId ＝ 改已有便签（重命名 + 编辑正文）。 */
function openNoteModal(noteId) {
  const mask = $('#noteModal'); if (!mask) return;
  const n = noteId ? (BOARD.notes.find(x => x.id === noteId) || null) : null;
  NOTE_EDIT_ID = n ? n.id : null;
  $('#noteTitle').value = n ? (n.title || '') : ($('#planNew').value || '').trim();  // 新建时把输入框里的字带进来当主题
  $('#noteBody').value = n ? (n.body || '') : '';
  $('#noteModalHint').textContent = '';
  $('#noteModalHead').textContent = n ? '编辑便签' : '贴一张便签';
  $('#noteConfirm').textContent = n ? '保存' : '贴上';
  $('#noteBody').placeholder = n ? '展开写：背景、要做的事、判断依据…（Ctrl+Enter 保存）' : '展开写：背景、要做的事、判断依据…（Ctrl+Enter 贴上）';
  mask.hidden = false;
  setTimeout(() => $('#noteBody').focus(), 30);
}
function closeNoteModal() {
  const mask = $('#noteModal'); if (mask) mask.hidden = true;
  $('#noteModalHint').textContent = '';
  NOTE_EDIT_ID = null;
}
function confirmNote() {
  const hint = $('#noteModalHint');
  const title = ($('#noteTitle').value || '').trim();
  const body = ($('#noteBody').value || '').trim();
  if (!title && !body) { hint.textContent = '主题或内容，至少写一样'; return; }
  if (!BOARD) { hint.textContent = '白板还没加载好，稍等再试'; return; }
  try {
    let id;
    if (NOTE_EDIT_ID) {                              // 编辑已有便签：只改标题与正文
      const n = BOARD.notes.find(x => x.id === NOTE_EDIT_ID);
      if (n) { n.title = title || '(无主题)'; n.body = body; }
      id = NOTE_EDIT_ID;
    } else {                                         // 新建：追加到最短的一列
      id = 'u' + Date.now();
      BOARD.notes.push({ id, title: title || '(无主题)', tags: ['待定'], body, points: [], more: '' });
      let shortest = 0;
      BOARD.cols.forEach((c, i) => { if (c.length < BOARD.cols[shortest].length) shortest = i; });
      BOARD.cols[shortest].push(id);
      $('#planNew').value = '';
    }
    closeNoteModal();
    renderWall(); saveBoard(); focusNote(id);
  } catch (err) {
    console.error('[planAdd] 保存便签失败：', err);
    hint.textContent = '保存便签出错：' + ((err && err.message) || err);
  }
}

